"""Write the copy-paste CI setup page, ``docs/Processes & Guides/Setup Snippets.md``.

Every snippet on the page is rendered by :mod:`testo_core.services.ci_templates`
(the code ``testo init`` writes CI files with) for a typical project of each
stack, so the page and the command can't drift apart. A contract test re-renders
it and fails when the committed page is stale.

Usage::

    python scripts/export_setup_snippets.py            # write the page
    python scripts/export_setup_snippets.py --check    # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PAGE_PATH = REPO_ROOT / "docs" / "Processes & Guides" / "Setup Snippets.md"
CYCLE = "my-app"

# A typical project per stack: the files detection reads (and the install step uses).
_SEEDS: dict[str, dict[str, str]] = {
    "pytest": {"requirements.txt": "pytest\n", "tests/test_app.py": ""},
    "jest": {"package.json": '{"devDependencies": {"jest": "*"}}', "package-lock.json": "{}"},
    "vitest": {"package.json": '{"devDependencies": {"vitest": "*"}}', "package-lock.json": "{}"},
    "playwright": {
        "package.json": '{"devDependencies": {"@playwright/test": "*"}}',
        "package-lock.json": "{}",
    },
    "go": {"go.mod": "module example.com/app\n"},
    "dotnet": {"App.Tests/App.Tests.csproj": "Microsoft.NET.Test.Sdk"},
    "maven": {"pom.xml": "<project/>"},
    "gradle": {"build.gradle": "", "gradlew": ""},
    "rspec": {"Gemfile": "gem 'rspec'\n"},
    "phpunit": {"composer.json": '{"require-dev": {"phpunit/phpunit": "*"}}'},
}

_TITLES = {
    "pytest": "Python (pytest)",
    "jest": "JavaScript (Jest)",
    "vitest": "JavaScript (Vitest)",
    "playwright": "Browser tests (Playwright)",
    "go": "Go (go test)",
    "dotnet": ".NET (dotnet test)",
    "maven": "Java (Maven)",
    "gradle": "Java or Kotlin (Gradle)",
    "rspec": "Ruby (RSpec)",
    "phpunit": "PHP (PHPUnit)",
}

_HEADER = """---
type: guide
status: current
created: 2026-11-01
updated: 2026-11-01
---

# Setup Snippets

<!-- Generated by scripts/export_setup_snippets.py from testo_core/services/ci_templates.py. Edit those, not this page. -->

Copy-paste CI setup for each test runner and each CI system. Every snippet runs your tests the way they already run, has the runner write a result file Testosterone reads, and records it with no `testosterone.yaml`. Replace `{cycle}` with your project's name: runs recorded under the same cycle build its history.

Rather not copy anything? In the project folder, `pip install testo-core && testo init` detects the runners and writes these files for you, plus a `testosterone.yaml` so `testo run` works locally too ([Command Reference § testo init](../CLI%20Commands/Command%20Reference.md#testo-init)). `testo init --ci gitlab --dry-run` prints one without writing it.

How each CI keeps the history between runs:

- **GitHub Actions**: the action caches it (`history: auto`) and comments on pull requests. Inputs: [CI-CD Pipeline Setup § GitHub Action](CI-CD%20Pipeline%20Setup.md#github-action).
- **GitLab CI** and **CircleCI**: the snippet caches `.testo-history/` per branch, falling back to the default branch's.
- **Jenkins**: the history stays in the agent's workspace. For one history across agents and CI systems, run a [team server](Team%20Server.md) and replace `testo ingest ...` with `testo ingest --server https://your-server --token "$TESTO_API_TOKEN" ...`.

Outside GitHub, the snippets install `testo` with [uv](https://docs.astral.sh/uv/) (one binary that brings its own Python, so the image needs only `curl`). An image that has Python can run `pip install testo-core` instead. Each run's summary is saved as `testo-summary.md` next to the build.
"""


def _facts(key: str):  # noqa: ANN202 - ProjectFacts, imported lazily
    from testo_core.services.project_setup import detect_project

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        for rel, text in _SEEDS[key].items():
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        facts = detect_project(root, only=[key])
    return facts


def render_page() -> str:
    from testo_core.services import ci_templates

    parts = [_HEADER.format(cycle=CYCLE)]
    for key, title in _TITLES.items():
        facts = _facts(key)
        parts.append(f"## {title}\n")
        (stack,) = facts.stacks
        parts.append(f"Test command: `{ci_templates.ci_test_command(stack)}`\n")
        blocks = [
            (
                "GitHub Actions",
                "`.github/workflows/tests.yml`",
                "yaml",
                ci_templates.zero_config_github_workflow(facts, cycle=CYCLE),
            ),
            ("GitLab CI", "`.gitlab-ci.yml`", "yaml", ci_templates.gitlab_ci(facts, cycle=CYCLE)),
            ("Jenkins", "`Jenkinsfile`", "groovy", ci_templates.jenkinsfile(facts, cycle=CYCLE)),
            (
                "CircleCI",
                "`.circleci/config.yml`",
                "yaml",
                ci_templates.circleci_config(facts, cycle=CYCLE),
            ),
        ]
        for name, path, lang, text in blocks:
            parts.append(f"### {title}: {name}\n\n{path}\n\n```{lang}\n{text}```\n")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Fail if the page is out of date.")
    args = parser.parse_args(argv)
    text = render_page()
    if args.check:
        current = PAGE_PATH.read_text(encoding="utf-8") if PAGE_PATH.exists() else ""
        if current != text:
            print(
                f"{PAGE_PATH} is stale: run python scripts/export_setup_snippets.py",
                file=sys.stderr,
            )
            return 1
        return 0
    PAGE_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
