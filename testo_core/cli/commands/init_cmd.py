"""``testo init`` — add Testosterone to a project in one command.

Plain ``testo init`` looks at the project (:mod:`testo_core.services.project_setup`):
which test runners it uses, from ``pyproject.toml``, ``package.json``,
``go.mod``, ``*.csproj``, ``pom.xml`` and friends. Then it writes

* ``testosterone.yaml`` with one cycle that runs each of them, set up so their
  results are read (Jest's JSON report, ``go test -json``, TRX, Surefire XML...),
* the CI workflow (``.github/workflows/testosterone.yml``) that runs the cycle
  with the GitHub Action and comments on pull requests,
* the ``.gitignore`` lines for Testosterone's local files,

and records a first run: the result files a test run already left in the
project when there are any, otherwise one ``testo run`` of the new cycle.
Files that exist are kept unless ``--force``; ``--dry-run`` prints instead.

``testo init --scan`` looks in every folder (:mod:`testo_core.services.repo_scan`),
for monorepos, shows the stages it found and asks before writing. ``--check``
asks each runner to list its tests (:mod:`testo_core.services.stage_check`) and
leaves out stages that have none.

``testo init --pr`` then commits what it wrote on a new branch, pushes it and
opens a pull request (:mod:`testo_core.services.setup_pr`); ``--dependabot``
also writes ``.github/dependabot.yml``.

``testo init --interactive`` is the older question-by-question wizard.
"""

from __future__ import annotations

import contextlib
import dataclasses
import json
import os
from collections.abc import Iterator
from pathlib import Path
from typing import TYPE_CHECKING

import typer
from rich.console import Console

from testo_core.config.json_schema import SCHEMA_ID
from testo_core.engine.exit_codes import EngineExitCode

if TYPE_CHECKING:
    from testo_core.services.project_setup import ProjectFacts, Stack


def wizard(path: Path | None) -> None:
    """Interactive scaffolding for a default testosterone.yaml (``testo init --interactive``)."""
    from testo_core.cli.ui.console import default_console

    console = default_console()
    out = path
    if out is None:
        out = Path(typer.prompt("Output file", default="testosterone.yaml")).expanduser()
    out = out.expanduser().resolve()

    if out.exists():
        overwrite = typer.confirm(f"{out} exists — overwrite?", default=False)
        if not overwrite:
            console.print("[fail]Aborted.[/]")
            raise typer.Exit(code=int(EngineExitCode.INVALID_INPUT))

    target_repo = typer.prompt("Default target_repo (relative to config dir)", default=".")
    artifacts = typer.prompt("artifacts_root", default="artifacts")
    workers = int(typer.prompt("Default workers", default="4"))
    timeout_s = int(typer.prompt("Default timeout_s", default="600"))
    cycle_name = typer.prompt("First cycle name", default="smoke")
    db_url = typer.prompt(
        "database.url (optional, leave empty to skip)", default="", show_default=False
    )
    db_block = ""
    if str(db_url).strip():
        db_block = f"database:\n  url: {json.dumps(str(db_url).strip())}\n\n"

    yaml_text = f"""# yaml-language-server: $schema={SCHEMA_ID}
version: 1
{db_block}defaults:
  target_repo: {json.dumps(str(Path(target_repo)))}
  artifacts_root: {json.dumps(str(artifacts))}
  timeout_s: {timeout_s}
  workers: {workers}

cycles:
  {cycle_name}:
    description: Generated by ``testo init``.
    stages:
      - name: api
        equipment: pytest
        args: ["-q", "--maxfail=1", "tests"]
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(yaml_text, encoding="utf-8")
    console.print(f"[ok]Wrote {out}[/]")
    raise typer.Exit(code=0)


CI_CHOICES = ("auto", "github", "gitlab", "jenkins", "circleci", "none")


@contextlib.contextmanager
def _cwd(path: Path) -> Iterator[None]:
    before = Path.cwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(before)


def _resolve_ci(choice: str, repo: Path) -> str:
    from testo_core.services.ci_templates import detect_ci

    choice = choice.strip().lower()
    if choice not in CI_CHOICES:
        raise typer.BadParameter(f"pick one of {', '.join(CI_CHOICES)}", param_hint="--ci")
    if choice != "auto":
        return choice
    return detect_ci(repo) or "github"


_INCLUDE_HINTS = {
    "gitlab": "add to .gitlab-ci.yml:  include: [{local: .gitlab/testosterone.gitlab-ci.yml}]",
    "jenkins": "copy its stages and post block into your Jenkinsfile",
    "circleci": "copy its job into .circleci/config.yml and add it to a workflow",
}


def _existing_cycle(config: Path, wanted: str) -> str:
    """The cycle to use from a config that was kept: *wanted* if it's there, else its only one."""
    from testo_core.config.loader import discover_and_load

    try:
        cycles = list(discover_and_load(config_path=config).cycles)
    except Exception:  # noqa: BLE001 — a broken config is reported by the run itself
        return wanted
    if wanted in cycles or len(cycles) != 1:
        return wanted
    return cycles[0]


def init(
    directory: Path = typer.Option(
        Path("."), "--dir", file_okay=False, help="The project to set up (default: here)."
    ),
    stack: list[str] = typer.Option(
        [],
        "--stack",
        help="Use this runner instead of detecting (repeatable): pytest, jest, vitest, "
        "playwright, go, dotnet, maven, gradle, rspec, phpunit.",
    ),
    cycle: str = typer.Option(
        None, "--cycle", help="Name of the cycle to write (default: the project folder's name)."
    ),
    ci: str = typer.Option(
        "auto",
        "--ci",
        help="CI file to write: github, gitlab, jenkins, circleci or none "
        "(auto = the CI the project already uses, else github).",
    ),
    run_first: bool = typer.Option(
        True,
        "--run/--no-run",
        help="Record a first run: existing result files if any, else run the new cycle once.",
    ),
    scan: bool = typer.Option(
        False,
        "--scan",
        help="Look in every folder, not just the top (monorepos): a stage per runner per "
        "project folder. Shows the stages and asks before writing.",
    ),
    check: bool = typer.Option(
        False,
        "--check",
        help="Ask each runner which tests it would run (pytest --collect-only, jest "
        "--listTests, go test -list...) and leave out stages with none. Loads your test "
        "code; never runs a test.",
    ),
    yes: bool = typer.Option(False, "--yes", "-y", help="With --scan: write without asking."),
    force: bool = typer.Option(False, "--force", help="Overwrite files that already exist."),
    dry_run: bool = typer.Option(
        False, "--dry-run", help="Print what would be written; write and run nothing."
    ),
    interactive: bool = typer.Option(
        False,
        "--interactive",
        help="The older wizard: asks for each value, writes only the config.",
    ),
    path: Path | None = typer.Option(
        None, "--path", help="With --interactive: output path (prompted when omitted)."
    ),
    open_pr: bool = typer.Option(
        False,
        "--pr",
        help="Then commit the written files on a new branch, push it and open a pull request "
        "(needs git and the GitHub CLI; without gh, prints the commands left).",
    ),
    server: str = typer.Option(
        "",
        "--server",
        help="Also upload every CI run to this team server (https://...). The workflow reads "
        "the token from the TESTO_API_TOKEN secret; with gh and $TESTO_API_TOKEN set, "
        "init stores the secret too.",
    ),
    dependabot: bool = typer.Option(
        False,
        "--dependabot",
        help="Also write .github/dependabot.yml (weekly GitHub Actions updates) when there is none.",
    ),
) -> None:
    """Detect the project's test runners, write testosterone.yaml and the CI workflow, record a first run."""
    if interactive:
        wizard(path)
        return

    from testo_core.cli.ui.console import default_console
    from testo_core.services import ci_templates, project_setup, repo_scan

    console = default_console()
    repo = directory.expanduser().resolve()
    unknown = [s for s in stack if s.strip().lower() not in project_setup.STACK_KEYS]
    if unknown:
        raise typer.BadParameter(
            f"unknown stack {unknown[0]!r}; pick from {', '.join(project_setup.STACK_KEYS)}",
            param_hint="--stack",
        )
    if scan:
        scanned = repo_scan.scan_repo(repo, only=stack)
        facts = dataclasses.replace(scanned.facts, skipped=scanned.notes)
    else:
        facts = project_setup.detect_project(repo, only=stack)
    if not facts.stacks:
        where = "any folder of " if scan else ""
        console.print(
            f"[fail]No test runner found in {where}{repo}.[/] Looked for pytest, Jest, Vitest, "
            "Playwright, go test, dotnet test, Maven, Gradle, RSpec and PHPUnit.\n"
            + ("" if scan else "Look in subfolders too with --scan. ")
            + "Name one with --stack, or record results you already have:\n"
            "  testo ingest 'reports/**/*.xml' --cycle tests"
        )
        raise typer.Exit(code=int(EngineExitCode.INVALID_INPUT))

    from testo_core.cli.server_url import server_url_problem

    server_url = (server or "").strip().rstrip("/")
    problem = server_url_problem(server_url) if server_url else None
    if problem:
        raise typer.BadParameter(problem, param_hint="--server")
    cycle_name = (cycle or "").strip() or project_setup.cycle_name_for(repo)
    if scan:
        _print_stages(console, facts)
    else:
        console.print("Found: " + ", ".join(s.label for s in facts.stacks))
    if check:
        facts = _check_stages(console, facts, repo)
    for note in facts.skipped:
        console.print(f"  [muted]Not added: {note}[/]")

    config_path = repo / "testosterone.yaml"
    keep_config = config_path.exists() and not force
    if keep_config:
        cycle_name = _existing_cycle(config_path, cycle_name)
    ci_kind = _resolve_ci(ci, repo)
    branch = ci_templates.default_branch(repo)
    files: list[tuple[Path, str, bool]] = [
        (config_path, project_setup.config_yaml(facts, cycle=cycle_name), keep_config)
    ]
    ci_hint = ""
    if ci_kind != "none":
        main_file, side_file = ci_templates.CI_FILES[ci_kind]
        target = repo / main_file
        if target.exists() and not force and side_file != main_file:
            # Never edit someone's pipeline: write ours next to it and say how to wire it in.
            target = repo / side_file
            ci_hint = _INCLUDE_HINTS[ci_kind]
        text = ci_templates.ci_file_text(
            ci_kind, facts, cycle=cycle_name, branch=branch, server=server_url
        )
        files.append((target, text, target.exists() and not force))
    if dependabot:
        from testo_core.services.setup_pr import DEPENDABOT_PATH, dependabot_yaml

        bot = repo / DEPENDABOT_PATH
        files.append((bot, dependabot_yaml(), bot.exists()))

    if dry_run:
        for target, text, keep in files:
            rel = target.relative_to(repo)
            state = " (exists, would be kept; --force overwrites)" if keep else ""
            console.print(f"\n[bold]--- {rel}{state}[/]")
            if not keep:
                console.print(text, markup=False, highlight=False, end="")
        return

    if scan and not yes:
        _confirm(console, [t.relative_to(repo) for t, _, keep in files if not keep], run_first)

    for target, text, keep in files:
        rel = target.relative_to(repo)
        if keep:
            console.print(f"Kept {rel} (exists; --force overwrites)")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        console.print(f"[ok]Wrote {rel}[/]")
    if ci_hint:
        console.print(f"Your CI file exists, so it was left alone; to use the new one, {ci_hint}")

    missing = project_setup.missing_gitignore_lines(repo)
    if missing:
        gitignore = repo / ".gitignore"
        before = gitignore.read_text(encoding="utf-8") if gitignore.exists() else ""
        sep = "" if not before or before.endswith("\n") else "\n"
        block = "# Testosterone's local history and run files\n" + "\n".join(missing) + "\n"
        gitignore.write_text(before + sep + block, encoding="utf-8")
        console.print(f"[ok]Added {', '.join(missing)} to .gitignore[/]")

    if server_url:
        _server_secret(console, repo=repo, ci_kind=ci_kind, server=server_url)

    code = 0
    if run_first:
        code = _first_run(console=console, repo=repo, cycle=cycle_name, config=config_path)

    written = [t.relative_to(repo).as_posix() for t, _, keep in files if not keep]
    if missing:
        written.append(".gitignore")
    if open_pr:
        if _publish(console, repo=repo, files=written, base=branch, cycle=cycle_name):
            raise typer.Exit(code=code)
        written = []  # _publish already said what is left to do
    console.print("\nNext:")
    if written:
        added = " ".join(written)
        console.print(f"  git add {added} && git commit -m 'ci: add Testosterone'")
        console.print("  (or next time: testo init --pr)")
    console.print(
        "  testo ui          # the run history in your browser (pip install 'testo-core\\[api]')"
    )
    console.print(f"  testo run --cycle {cycle_name}")
    raise typer.Exit(code=code)


def _server_secret(console: Console, *, repo: Path, ci_kind: str, server: str) -> None:
    """``--server``: store ``$TESTO_API_TOKEN`` as the repository secret the workflow reads."""
    from testo_core.services.ci_templates import SERVER_TOKEN_SECRET
    from testo_core.services.setup_pr import set_repo_secret

    if ci_kind != "github":
        console.print(
            f"To upload to {server} from {ci_kind}, add `--server {server}` to the testo ingest "
            f"step and give the job a {SERVER_TOKEN_SECRET} variable (masked)."
        )
        return
    token = os.environ.get(SERVER_TOKEN_SECRET, "").strip()
    if not token:
        console.print(
            f"The workflow uploads to {server} with the {SERVER_TOKEN_SECRET} secret. Add it "
            f"(Settings → Secrets and variables → Actions), or run init again with "
            f"{SERVER_TOKEN_SECRET} set and gh installed to store it."
        )
        return
    error = set_repo_secret(repo, SERVER_TOKEN_SECRET, token)
    if error:
        console.print(f"[warn]Couldn't store the {SERVER_TOKEN_SECRET} secret: {error}[/]")
    else:
        console.print(f"[ok]Stored {SERVER_TOKEN_SECRET} as a repository secret[/]")


def _publish(console: Console, *, repo: Path, files: list[str], base: str, cycle: str) -> bool:
    """``--pr``: branch, commit, push, pull request. True when the pull request is open."""
    from testo_core.services.setup_pr import open_setup_pr

    if not files:
        console.print("\nNothing new was written, so there is no pull request to open.")
        return False
    console.print(f"\nOpening a pull request into {base} with: {', '.join(files)}")
    result = open_setup_pr(repo, files=files, base=base, cycle=cycle)
    if result.url:
        console.print(f"[ok]Opened {result.url}[/] (branch {result.branch})")
        console.print(
            "Its comment has no baseline yet: merge it, and pull requests after the first "
            f"run on {base} are compared with it."
        )
        return True
    console.print(f"[warn]Couldn't finish the pull request: {result.error}[/]")
    if result.todo:
        console.print("Left to do:")
        for line in result.todo:
            console.print(f"  {line}", markup=False, highlight=False)
    return False


def _print_stages(console: Console, facts: ProjectFacts) -> None:
    """The stages ``--scan`` proposes: folder, runner, and the command each one runs."""
    from testo_core.services.ci_templates import ci_test_command

    console.print(f"Found {len(facts.stacks)} test suite(s):")
    for stack in facts.stacks:
        folder = str(stack.stage.get("target_repo") or ".")
        bare = dataclasses.replace(
            stack, stage={k: v for k, v in stack.stage.items() if k != "target_repo"}
        )
        console.print(
            f"  [bold]{stack.stage['name']}[/]  {stack.label} in {folder}/\n"
            f"      [muted]{ci_test_command(bare)}[/]",
            highlight=False,
        )


def _check_stages(console: Console, facts: ProjectFacts, repo: Path) -> ProjectFacts:
    """List each stage's tests with its runner; stages that list none are left out."""
    from testo_core.services.stage_check import check_stage

    console.print("\nChecking with each runner (lists tests, runs none):")
    kept: list[Stack] = []
    notes = list(facts.skipped)
    for stack in facts.stacks:
        result = check_stage(stack, root=repo)
        style = {"ok": "ok", "empty": "fail", "error": "warn"}.get(result.status, "muted")
        console.print(f"  {stack.stage['name']}: [{style}]{result.summary}[/]", highlight=False)
        if result.status == "empty":
            notes.append(f"{stack.stage['name']}: {stack.label} found no tests there")
        else:
            kept.append(stack)
    if not kept:
        console.print("[fail]No proposed stage has tests, so nothing was written.[/]")
        raise typer.Exit(code=int(EngineExitCode.INVALID_INPUT))
    return dataclasses.replace(facts, stacks=tuple(kept), skipped=tuple(notes))


def _confirm(console: Console, files: list[Path], run_first: bool) -> None:
    """Ask before ``--scan`` writes anything; no answer (no terminal) means no."""
    if files:
        console.print("\nWill write: " + ", ".join(str(f) for f in files))
    if run_first:
        console.print("Then records a first run (--no-run skips it).")
    try:
        ok = typer.confirm("Go ahead?", default=True)
    except typer.Abort:
        ok = False
    if not ok:
        console.print(
            "Nothing written. See the files in full with --dry-run; skip this with --yes."
        )
        raise typer.Exit(code=int(EngineExitCode.INVALID_INPUT))


def _first_run(*, console: Console, repo: Path, cycle: str, config: Path) -> int:
    """Record the results already on disk, else run *cycle* once. Failing tests still count as recorded."""
    from testo_core.cli.runner import execute_ingest_command, execute_plan_command
    from testo_core.services.project_setup import find_result_files, result_patterns

    found = find_result_files(repo)
    with _cwd(repo):
        if found:
            reports = result_patterns(found, repo=repo)
            console.print(
                f"\nRecording the results already here as a first run: {', '.join(reports)}"
            )
            code = execute_ingest_command(
                console=console,
                reports=reports,
                cycle=cycle,
                stage="junit",
                tier="unit",
                repo=repo,
                config_path=config,
                ci=False,
                persist=True,
            )
        else:
            console.print(
                f"\nNo result files yet, so running the {cycle!r} cycle once (skip with --no-run)"
            )
            code = execute_plan_command(
                console=console,
                plan_name=cycle,
                config_path=config,
                stream=False,
                ci=False,
                persist=True,
                workers_override=None,
            )
    # 1 means a test failed: the run was still recorded, which is what init is for.
    return 0 if code == int(EngineExitCode.DOMAIN_FAILURE) else code
